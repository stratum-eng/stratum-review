import type { D1BoundStatement, DbEnv } from "./env";

export type SqlStatement = { sql: string; params?: unknown[] };

// Queries are written with Postgres-style $n placeholders, which keeps the diff against upstream small; D1 spells them ?n.
function toD1Sql(sqlText: string) {
  return sqlText.replace(/\$(\d+)/g, "?$1");
}

// Arrays go in as JSON text and are read back with json_each, D1's replacement for Postgres array parameters.
function normalizeParam(param: unknown): unknown {
  if (param === undefined) return null;
  if (typeof param === "boolean") return param ? 1 : 0;
  if (Array.isArray(param)) return JSON.stringify(param);
  return param;
}

function prepare(env: Pick<DbEnv, "DB">, statement: SqlStatement) {
  return env.DB.prepare(toD1Sql(statement.sql)).bind(
    ...(statement.params ?? []).map(normalizeParam),
  );
}

// D1 holds no per-request connection, so this only keeps the call sites' shape.
export function runWithDb<E, T>(_env: E, fn: () => T): T {
  return fn();
}

export async function queryRows<T>(
  env: Pick<DbEnv, "DB">,
  sqlText: string,
  params: unknown[] = [],
): Promise<T[]> {
  const { results } = await prepare(env, { sql: sqlText, params }).all<T>();
  return results ?? [];
}

/**
 * D1's only multi-statement transaction: statements run in order and any failure rolls back all of
 * them. A statement cannot see an earlier one's result, so ids that later statements need are either
 * generated by the caller or looked up by subquery. Returns each statement's rows, by position.
 */
export async function queryBatch(
  env: Pick<DbEnv, "DB">,
  statements: SqlStatement[],
): Promise<unknown[][]> {
  if (statements.length === 0) return [];
  const bound: D1BoundStatement[] = statements.map((s) => prepare(env, s));
  const results = await env.DB.batch(bound as never[]);
  return results.map((r) => r.results ?? []);
}

export function parseJsonColumn<T>(
  value: T | string | null | undefined,
  fallback: T,
): T {
  if (value === null || value === undefined) return fallback;
  if (typeof value === "string") return JSON.parse(value) as T;
  return value;
}
